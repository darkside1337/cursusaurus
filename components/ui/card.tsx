import * as React from "react"
import { cn } from "cn"

function Card({
  className,
  size = "default",
  ...props
}: React.ComponentProps<"div"> & { size?: "default" | "sm" }) {
  return (
    <div
      data-slot="card"
      data-size={size}
      className={cn(
        "group/card flex flex-col gap-4 overflow-hidden rounded-cards border border-[#ececec] bg-paper-white font-sohne text-ink-black transition-shadow duration-200 hover:shadow-subtle",
        className
      )}
      {...props}
    />
  )
}

